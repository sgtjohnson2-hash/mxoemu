MarginSocket::MarginSocket(ISocketHandler& h) : TCPVarLenSocket(h)
{
	memset(challenge,0,sizeof(challenge));
	charId = 0;
	sessionId = 0;
	worldCharId = 0;
	numCharacterReplies = 0;
	readyForUdp = false;
	m_connState = MARGIN_STATE_WAIT_CONNECT_REQ;
}

MarginSocket::~MarginSocket()
{
}

void MarginSocket::OnDisconnect( short info, int code )
{
	if (sessionId != 0)
	{
		std::shared_ptr<GameClient> udpClient = sGame.GetClientWithSessionId(sessionId);
		if (udpClient)
		{
			if (udpClient->GetPlayerGoId() == 0 && udpClient->GetCharacterId() == 0)
			{
				udpClient->Invalidate();
			}
			else
			{
				INFO_LOG(format("Margin socket with %1% disconnected (session %2%), preserving active in-world UDP client (player GOID %3%)")
					% GetRemoteSocketAddress()->Convert(true) % sessionId % udpClient->GetPlayerGoId());
			}
		}
		DEBUG_LOG(format("Margin socket with %1% disconnected (session %2%)") % GetRemoteSocketAddress()->Convert(true) % sessionId);
	}
}

void MarginSocket::SendCrypted( TwofishEncryptedPacket &cryptedPacket )
{
	if (m_tfEngine.IsValid())
	{
		SendPacket(TCPVariableLengthPacket(cryptedPacket.toCipherText(m_tfEngine)));
	}
}

enum MarginOpcode
{
	CERT_ConnectRequest = 0x01,
	CERT_Challenge = 0x02,
	CERT_ChallengeResponse = 0x03,
	CERT_ConnectReply = 0x04,
	CERT_NewSessionKey = 0x05,
	MS_ConnectRequest = 0x06,
	MS_ConnectChallenge = 0x07,
	MS_ConnectChallengeResponse = 0x08,
	MS_ConnectReply = 0x09,
	MS_ClaimCharacterNameRequest = 0x0A,
	MS_ClaimCharacterNameReply = 0x0B,
	MS_CreateCharacterRequest = 0x0C,
	MS_DeleteCharacterRequest = 0x0D,
	MS_DeleteCharacterReply = 0x0E,
	MS_LoadCharacterRequest = 0x0F,
	MS_LoadCharacterReply = 0x10,
	MS_EstablishUDPSessionReply = 0x11,
	MS_RefreshSessionKeyRequest = 0x12,
	MS_RefreshSessionKeyReply = 0x13,
	MS_ServerShuttingDown = 0x14,
	MS_FailoverRequest = 0x15,
	MS_FailoverReply = 0x16,
	MS_AdjustFloodgateRequest = 0x17,
	MS_AdjustFloodgateReply = 0x18,
	MS_GetPlayerListRequest = 0x19,
	MS_GetPlayerListReply = 0x1A,
	MS_FakePopulationRequest = 0x1B,
	MS_UnloadCharacterRequest = 0x1C,
	MS_GetClientIPRequest = 0x1D,
	MS_GetClientIPReply  = 0x1E
};

void MarginSocket::ProcessData( const byte *buf,size_t len )
{
	if (len == 0 || buf == nullptr)
		return;

	try
	{
		ByteBuffer packetContents(buf,len);

		DEBUG_LOG(format("Margin Receieved |%1%|") % Bin2Hex(packetContents) );

		bool encrypted = true;

		byte firstByte = 0;
		if (packetContents.remaining() >= 1)
		{
			packetContents >> firstByte;
			if (firstByte == CERT_ConnectRequest && packetContents.remaining() >= 2)
			{
				uint16 firstShort;
				packetContents >> firstShort;

				if (firstShort == 3)
				{
					encrypted = false;
				}
			}
			else if (firstByte == CERT_ChallengeResponse && len == 17)
			{
				encrypted = false;
			}
			else if (!m_tfEngine.IsValid())
			{
				encrypted = false;
			}
		}
		//reset position
		packetContents.rpos(0);

		ByteBuffer packetData;

		if (encrypted == true && m_tfEngine.IsValid())
		{
			try
			{
				TwofishEncryptedPacket packetTodecrypt(packetContents,m_tfEngine);
				packetData = packetTodecrypt;

				DEBUG_LOG(format("Margin Decrypted |%1%|") % Bin2Hex(packetData) );
			}
			catch (std::exception &e)
			{
				ERROR_LOG(format("Margin Decrypt failed: %1%") % e.what());
				SetCloseAndDelete(true);
				return;
			}
		}
		else
		{
			packetData = packetContents;
		}

		if (packetData.remaining() < 1)
		{
			SetCloseAndDelete(true);
			return;
		}

		byte packetOpcode;
		packetData >> packetOpcode;
		MarginOpcode opcode = MarginOpcode(packetOpcode);

		if (opcode != CERT_ConnectRequest && opcode != CERT_ChallengeResponse)
		{
			if (m_connState != MARGIN_STATE_AUTHENTICATED && m_connState != MARGIN_STATE_IN_GAME)
			{
				WARNING_LOG(format("MarginSocket: Opcode 0x%1$02X received before authentication (state=%2%), disconnecting")
					% (uint32)packetOpcode % (uint32)m_connState);
				SetCloseAndDelete(true);
				return;
			}
		}

	switch (opcode)
	{
	default:
		{
			DEBUG_LOG(format("MarginSocket: Unknown opcode 0x%1$02X from client, disconnecting") % (uint32)packetOpcode);
			SetCloseAndDelete(true);
			break;
		}
	case CERT_ConnectRequest:
		{
			uint16 firstNumber;
			if (packetData.remaining() < sizeof(firstNumber))
			{
				SetCloseAndDelete(true);
				return;
			}
			packetData >> firstNumber;

			if (firstNumber != 3)
			{
				WARNING_LOG(format("CERT_ConnectRequest first num not 3 (actually %1%)") % firstNumber);
			}

			uint16 authStart;
			if (packetData.remaining() < sizeof(authStart))
			{
				SetCloseAndDelete(true);
				return;
			}
			packetData >> authStart;

			if (authStart != swap16(0x3601) && authStart != swap16(0x3201))
			{
				WARNING_LOG(format("CERT_ConnectRequest auth start not 36 01 or 32 01: 0x%1$04X") % authStart);
			}

			byte signature[128];
			if (packetData.remaining() < sizeof(signature))
			{
				ERROR_LOG(format("CERT_ConnectRequest remaining %1% < signature %2%, disconnecting") % packetData.remaining() % sizeof(signature));
				SetCloseAndDelete(true);
				return;
			}
			packetData.read(signature,sizeof(signature));

			signedDataStruct signedData;
			memset(&signedData, 0, sizeof(signedData));
			// 2005 client: "32 01" + 178-byte ticket. 7.6005 client: "36 01" + 182 bytes
			// (same layout plus a trailing u32 account creation time). The signature covers all of it.
			const size_t ticketSize = (authStart == swap16(0x3601)) ? 182 : 178;
			size_t availableSignedData = packetData.remaining();
			if (availableSignedData < ticketSize)
			{
				ERROR_LOG(format("CERT_ConnectRequest remaining %1% < %2% bytes, disconnecting") % availableSignedData % ticketSize);
				SetCloseAndDelete(true);
				return;
			}
			byte ticket[182];
			memset(ticket, 0, sizeof(ticket));
			packetData.read(ticket, ticketSize);
			memcpy(&signedData, ticket, std::min(sizeof(signedData), ticketSize));
			size_t toRead = ticketSize;

			//verify signature, but first we need to md5
			CryptoPP::Weak::MD5 md5Object;
			md5Object.Update(ticket, ticketSize);
			byte verifyMePlease[16];
			md5Object.Final(verifyMePlease);
			bool signatureValid = sAuth.VerifyWith1024Bit(verifyMePlease,sizeof(verifyMePlease),signature,sizeof(signature));

			INFO_LOG(format("CERT_ConnectRequest: user=%1%, userId=%2%, toRead=%3%, signatureValid=%4%")
				% signedData.userName % signedData.userId1 % toRead % signatureValid);

			if (signatureValid == false)
			{
				WARNING_LOG("CERT_ConnectRequest signature invalid, allowing connection in emulator mode");
			}

			uint32 currTime = getTime();
			if (signedData.expiryTime < currTime) //the authentication session has expired
			{
				WARNING_LOG(format("CERT_ConnectRequest timestamp expired (%1% < %2%), continuing") % signedData.expiryTime % currTime);
			}

			m_userId = signedData.userId1;
			m_username = signedData.userName;

			//scope for db ptr
			{
				PreparedStatement stmt("SELECT `userId`, `username` FROM `users` WHERE LOWER(`username`) = LOWER(?0) LIMIT 1");
				stmt.SetString(0, m_username);
				scoped_ptr<QueryResult> result(sDatabase.QueryPrepared(&stmt));
				if (result == NULL)
				{
					INFO_LOG(format("CERT_ConnectRequest: Username %1% doesn't exist, disconnecting.") % m_username );
					SetCloseAndDelete(true);
					return;
				}

				Field *field = result->Fetch();
				uint32 dbUserId = field[0].GetUInt32();
				if (m_userId != dbUserId)
				{
					WARNING_LOG(format("CERT_ConnectRequest: UserId from packet %1% mismatches DB %2%, adopting DB userId.") % m_userId % dbUserId);
					m_userId = dbUserId;
				}
			}

			//we need to generate a twofish key for usage for encrypted margin/world, and a challenge so we can verify that client can encrypt fine
			CryptoPP::AutoSeededRandomPool randPool;
			//generate random twofish key and challenge
			randPool.GenerateBlock(twofishKey,sizeof(twofishKey));
			randPool.GenerateBlock(challenge,sizeof(challenge));

			//since we now have key, lets initialize our encryptor/decryptor
			m_tfEngine.Initialize(twofishKey,sizeof(twofishKey));

			//the rsa encrypted packet is 00 then twofish key then challenge, so its 31 bytes
			ByteBuffer tobeRSAd;
			tobeRSAd << uint8(0);
			tobeRSAd.append(twofishKey,sizeof(twofishKey));
			tobeRSAd.append(challenge,sizeof(challenge));

			//make CryptoPP integers out of our exponent and modulus
			CryptoPP::Integer exponent( uint32( swap16(signedData.publicExponent) ) );

			CryptoPP::Integer modulus;
			modulus.Decode(signedData.modulus,sizeof(signedData.modulus));

			CryptoPP::RSA::PublicKey userPubKey;
			userPubKey.Initialize(modulus,exponent);

			CryptoPP::RSAES_OAEP_SHA_Encryptor rsaEncryptor(userPubKey);

			string encryptedOutput;
			CryptoPP::StringSource(string(tobeRSAd.contents(),tobeRSAd.size()),
				true, 
				new CryptoPP::PK_EncryptorFilter(randPool, rsaEncryptor, new CryptoPP::StringSink(encryptedOutput)));

			//now that we have the encrypted keys, we can respond
			TCPVariableLengthPacket response;
			response << uint8(CERT_Challenge)
				<< uint16(3)
				<< uint16(encryptedOutput.size());
			response.append(encryptedOutput);

			SendPacket(response);
			
			DEBUG_LOG(format("Sending CERT_Challenge: |%1%|") % Bin2Hex(response) );
			m_connState = MARGIN_STATE_WAIT_CHALLENGE_RESP;
			break;
		}
	case CERT_ChallengeResponse:
		{
			if (m_connState != MARGIN_STATE_WAIT_CHALLENGE_RESP)
			{
				DEBUG_LOG("CERT_ChallengeResponse received out of order or without prior CERT_ConnectRequest, disconnecting");
				SetCloseAndDelete(true);
				return;
			}

			byte clientsChallenge[16];
			if (packetData.remaining() < sizeof(clientsChallenge))
			{
				SetCloseAndDelete(true);
				return;
			}
			packetData.read(clientsChallenge,sizeof(clientsChallenge));

			if (!memcmp(clientsChallenge,challenge,sizeof(challenge)))
			{
				DEBUG_LOG("CERT_ChallengeResponse from client correct!");
				m_connState = MARGIN_STATE_AUTHENTICATED;
			}
			else
			{
				ERROR_LOG("CERT_ChallengeResponse from client INcorrect!");
				DEBUG_LOG(format("Expected challenge: |%1%|, Got: |%2%|")
					% Bin2Hex(challenge, sizeof(challenge))
					% Bin2Hex(clientsChallenge, sizeof(clientsChallenge)));
				SetCloseAndDelete(true);
				return;
			}

			TwofishEncryptedPacket response; // 04 00 00 00 00 response from real server
			response << uint8(CERT_ConnectReply)
				<< uint32(0); // error code possibly ?

			SendCrypted(response);

			DEBUG_LOG(format("Sending CERT_ConnectReply: |%1%|") % Bin2Hex(response) );
			break;
		}
	case MS_ClaimCharacterNameRequest:
		{
			HandleClaimCharacterNameRequest(packetData);
			break;
		}
	case MS_CreateCharacterRequest:
		{
			HandleCreateCharacterRequest(packetData);
			break;
		}
	case MS_DeleteCharacterRequest:
		{
			HandleDeleteCharacterRequest(packetData);
			break;
		}
	case MS_ConnectRequest:
		{
			if (packetData.remaining() < 2*sizeof(uint32))
				break;

			uint32 matrixVersion;
			packetData >> matrixVersion;
			uint32 clientDllVersion;
			packetData >> clientDllVersion;

			//skip 9 bytes as we dont know what it is
			if (packetData.remaining() < 9)
				break;
			packetData.rpos(packetData.rpos()+9);

			//16 bytes weird sequence of bytes
			if (packetData.remaining() < sizeof(weirdSequenceOfBytes))
				break;
			packetData.read(weirdSequenceOfBytes,sizeof(weirdSequenceOfBytes));

			//ending 00
			if (packetData.remaining() < sizeof(uint8))
				break;

			uint8 lastByte;
			packetData >> lastByte;
			if (lastByte != 0)
			{
				WARNING_LOG(format("MS_ConnectRequest: last byte is not 0, but %1%") % uint32(lastByte));
			}
			
			DEBUG_LOG(format("MS_ConnectRequest: matrixVersion: %2% clientDllVersion: %2% rest: %3%")
				% ClientVersionString(matrixVersion)
				% ClientVersionString(clientDllVersion)
				% Bin2Hex(&packetData.contents()[packetData.rpos()],packetData.remaining()));

			//real server response with MS_ConnectChallenge which has 16 bytes some data, then 00 00 01 00
			TwofishEncryptedPacket response;
			response << uint8(MS_ConnectChallenge);
			//lets use a buffer full of FFs
			byte md5Buf[16];
			memset(md5Buf,0xFF,sizeof(md5Buf));
			response.append(md5Buf,sizeof(md5Buf));
			response << uint16(0); //md5 param 1
			response << uint16(1); //md5 param 2

			SendCrypted(response);

			DEBUG_LOG(format("Sending MS_ConnectChallenge: |%1%|") % Bin2Hex(response) );
			break;
		}
	case MS_ConnectChallengeResponse:
		{
			vector<byte> gameFilesMd5(CryptoPP::Weak::MD5::DIGESTSIZE);
			if (packetData.remaining() < gameFilesMd5.size())
				break;

			packetData.read(&gameFilesMd5[0],gameFilesMd5.size());

			//always accept
			//we need to send something like 09 00 00 00 00 00 00 00 00 29 A6 34 E9 0F 00 03 00 0C 00 07 00 A9 00
			//                                                          ?? ?? ?? ?? <- this part changes, its margin/world session id
			TwofishEncryptedPacket response;
			response << uint8(MS_ConnectReply);
			response << uint32(0);
			response << uint32(0);
			uint32 randMax = 0xFFFFFFFF;
			sessionId = MTRand::getSingleton().randInt(randMax);
			response << sessionId;
			response << uint16(0x0F);
			response << uint16(3);
			response << uint16(0x0C);
			response << uint16(7);
			response << uint16(0xA9);

			SendCrypted(response);

			readyForUdp = true;

			DEBUG_LOG(format("Sending MS_ConnectReply: |%1%|") % Bin2Hex(response) );
			break;
		}
	case MS_LoadCharacterRequest:
		{
			uint64 prevCharId = charId;
			// Try reading 8-byte charId from packet header (bytes 1..8)
			if (packetData.remaining() >= sizeof(charId))
			{
				packetData >> charId;
			}

			// If charId in header was 0, check offset 9 (MxoCharacterData format from matrix.exe)
			if (charId == 0 && packetData.size() >= 13)
			{
				uint32 charId32 = *reinterpret_cast<const uint32*>(&packetData.contents()[9]);
				if (charId32 != 0)
				{
					charId = charId32;
					DEBUG_LOG(format("MS_LoadCharacterRequest: Extracted charId %1% from MxoCharacterData at offset 9") % charId);
				}
			}

			// If packet charId is still 0, preserve charId set earlier in the session (e.g. HandleCreateCharacterRequest)
			if (charId == 0 && prevCharId != 0)
			{
				charId = prevCharId;
				INFO_LOG(format("MS_LoadCharacterRequest: Using session charId %1% from character creation") % charId);
			}

			// Scope for db ptr
			{
				scoped_ptr<QueryResult> result;
				if (charId != 0)
				{
					PreparedStatement stmt("SELECT `charId`, `userId`, `handle`, `firstName`, `lastName`, `background` FROM `characters` WHERE `userId` = ?0 AND `charId` = ?1 LIMIT 1");
					stmt.SetUInt32(0, m_userId);
					stmt.SetUInt32(1, (uint32)charId);
					result.reset(sDatabase.QueryPrepared(&stmt));
				}
				else
				{
					PreparedStatement stmt("SELECT `charId`, `userId`, `handle`, `firstName`, `lastName`, `background` FROM `characters` WHERE `userId` = ?0 ORDER BY `charId` DESC LIMIT 1");
					stmt.SetUInt32(0, m_userId);
					result.reset(sDatabase.QueryPrepared(&stmt));
				}

				if (result == NULL)
				{
					ERROR_LOG(format("MS_LoadCharacterRequest: Character doesn't exist or username %1% doesn't own it (charId=%2%, userId=%3%)")
						% m_username % charId % m_userId);
					SetCloseAndDelete(true);
					return;
				}

				Field *field = result->Fetch();
				charId = field[0].GetUInt32();
				m_charName = field[2].GetString();
				m_firstName = field[3].GetString();
				m_lastName = field[4].GetString();

				if (field[5].GetString() != NULL)
					m_background = field[5].GetString();
				else
					m_background = string();

				INFO_LOG(format("MS_LoadCharacterRequest: Successfully authenticated character '%1%' (charId=%2%) for user '%3%' (userId=%4%)")
					% m_charName % charId % m_username % m_userId);
			}

			// Clean up any stale sessions for this character so reconnecting operative loads cleanly
			auto allUsers = sGame.GetClientsWithCharacterId(charId);
			if (!allUsers.empty())
			{
				INFO_LOG(format("MS_LoadCharacterRequest: Character '%1%' (charId=%2%) has %3% existing session(s), invalidating stale session(s)")
					% m_charName % charId % allUsers.size());
				for (auto& oldClient : allUsers)
				{
					if (oldClient)
					{
						uint32 oldGo = oldClient->GetPlayerGoId();
						if (oldGo != 0)
						{
							sCombatSys.EndInterlock(oldGo, false);
						}
						oldClient->Invalidate();
					}
				}
			}

			SendLoadCharacterReplies();
			break;
		}
	}
	}
	catch (const ByteBuffer::out_of_range& e)
	{
		ERROR_LOG(format("MarginSocket::ProcessData ByteBuffer::out_of_range: %1%") % e.what());
		SetCloseAndDelete(true);
	}
	catch (const std::exception& e)
	{
		ERROR_LOG(format("MarginSocket::ProcessData exception: %1%") % e.what());
		SetCloseAndDelete(true);
	}
	catch (...)
	{
		ERROR_LOG("MarginSocket::ProcessData unknown exception");
		SetCloseAndDelete(true);
	}
}

void MarginSocket::SendCharacterReply( uint16 shortAfterId,bool lastPacket,uint8 opcode,ByteBuffer theData )
{
	numCharacterReplies++;

	TwofishEncryptedPacket derp;
	derp << uint8(MS_LoadCharacterReply)
		 << uint32(0)
		 << uint32(worldCharId)
		 << uint16(shortAfterId)
		 << uint8(numCharacterReplies)
		 << uint8(lastPacket)
		 << uint8(opcode);
	derp.append(&theData.contents()[theData.rpos()],theData.remaining());

	SendCrypted(derp);
}

bool MarginSocket::UdpReady(GameClient *theClient)
{
	if (!readyForUdp)
		return false;

	TwofishEncryptedPacket response;
	response << uint8(MS_EstablishUDPSessionReply)
		     << uint32(0);

	SendCrypted(response);
	return true;
}

// ---- Character data sections built from the character's own rows -------------------------
// The load-character replies used to be captured byte arrays, so every character's client showed
// the same retail inventory and ability loadout whatever the server held for them.
// Section framing (HDS MarginClient.SendMarginCharData): [0x10 0x00][u16 length][entries].

// Margin.DbInventory = 0 falls back to the old captured inventory.
// Entry (HDS MarginClient.loadInventory, matches the capture): [slot u8][item id u32][u32 flags]
// flags: stack count << 18 for stacks (capture: 04 00 = 1, 08 00 = 2, 4c 00 = 19);
//        otherwise purity << 26 (HDS default 00 00 00 0c).
static ByteBuffer BuildMarginInventorySection(uint64 charId)
{
	ByteBuffer entries;
	PreparedStatement stmt("SELECT `goid`, `slot`, `item_metadata` FROM `inventory` WHERE `charId` = ?0 ORDER BY `slot`");
	stmt.SetUInt64(0, charId);
	scoped_ptr<QueryResult> result(sDatabase.QueryPrepared(&stmt));
	int count = 0;
	if (result)
	{
		do
		{
			Field *field = result->Fetch();
			const uint32 goId = field[0].GetUInt32();
			const uint8 slot = field[1].GetUInt8();
			const std::string metadata = field[2].GetString();
			shared_ptr<Item> item(new Item(goId, sDataLoader.GetItemTemplate(goId) ? goId : 1));
			ItemSerializer::Deserialize(item, metadata);
			const uint32 templateId = item->getTemplateId();
			if (templateId <= 1)
				continue; // no client item behind it
			const uint16 stack = item->getStackCount();
			const uint32 flags = stack > 1 ? (uint32(stack & 0xFF) << 18) : 0x0C000000u;
			entries << uint8(slot) << uint32(templateId) << uint32(flags);
			count++;
		} while (result->NextRow());
	}
	ByteBuffer out;
	out << uint8(0x10) << uint8(0x00) << uint16(entries.size());
	if (entries.size())
		out.append(entries.contents(), entries.size());
	DEBUG_LOG(format("Margin: inventory section for char %1%: %2% items") % charId % count);
	return out;
}

// Ability entries: [slot u16][client ability GOID + level]; GOID = 0x80000000 + AbilityID * 0x400
// (hd_reference/data/abilityIDs.csv). A loaded entry's slot is the ability's index in the known list.
// Retail 7.6005 client.dll (0x621DE5B0 / 0x621CD550 / 0x621E0BD4): CPlayerAbilityMgr (0x629EA4E8)
// stores known ability entries in a fixed 520-element (0x0208) array of 8-byte structs at +0x06DC..+0x171B,
// immediately followed at +0x171C (0x629EBC04) by the std::vector for rl.cfg recipes (0x621DDA60).
// Unpacker 0x621CD550 writes `mov [ecx + esi*8 + 0x6dc], edi` without a `< 0x0208` check, so any
// slot >= 0x0208 overwrites 0x629EBC04 (`vector._Myfirst`) and crashes at client.dll+0x1DDAE4!
static constexpr uint16 kMaxClientAbilitySlots = 0x0208; // 520 slots (0x0000 .. 0x0207)
struct MarginAbility { uint16 slot; uint32 abilityId; uint16 level; };
static std::vector<MarginAbility> DecodeMarginAbilities(const unsigned char* data, size_t len)
{
	std::vector<MarginAbility> out;
	if (len < 4 || data[0] != 0x10) return out;
	const size_t n = std::min<size_t>(len - 4, size_t(data[2]) | (size_t(data[3]) << 8));
	for (size_t k = 0; k + 6 <= n; k += 6)
	{
		const unsigned char* e = data + 4 + k;
		const uint16 slot = uint16(e[0]) | (uint16(e[1]) << 8);
		if (slot >= kMaxClientAbilitySlots) continue;
		const uint32 val = uint32(e[2]) | (uint32(e[3]) << 8) | (uint32(e[4]) << 16) | (uint32(e[5]) << 24);
		MarginAbility a;
		a.slot = slot;
		a.abilityId = (val - 0x80000000u) >> 10;
		a.level = uint16((val - 0x80000000u) & 0x3FF);
		out.push_back(a);
	}
	return out;
}
static ByteBuffer EncodeMarginAbilities(const std::vector<MarginAbility> &list)
{
	ByteBuffer entries;
	for (const MarginAbility &a : list)
	{
		if (a.slot >= kMaxClientAbilitySlots) continue;
		entries << uint16(a.slot) << uint32(0x80000000u + (a.abilityId << 10) + (a.level & 0x3FF));
	}
	ByteBuffer out;
	out << uint8(0x10) << uint8(0x00) << uint16(entries.size());
	if (entries.size())
		out.append(entries.contents(), entries.size());
	return out;
}
// Known = captured known list + any loadout ability it lacks (inserted into free/unloaded slots < 0x0208).
// Loaded = captured loadout (innates like Hyper Jump / Hyper Sprint) + the character's own loadout
// from `abilities`, each at its known-list slot. Margin.DbAbilities = 0 sends the captures unchanged.
static void BuildMarginAbilitySections(uint64 charId, const unsigned char* knownCap, size_t knownLen,
	const unsigned char* loadedCap, size_t loadedLen, ByteBuffer &knownOut, ByteBuffer &loadedOut)
{
	std::vector<MarginAbility> known = DecodeMarginAbilities(knownCap, knownLen);
	std::vector<MarginAbility> loaded = DecodeMarginAbilities(loadedCap, loadedLen);
	std::map<uint32, size_t> knownIdx;
	std::set<uint16> usedSlots;
	for (size_t i = 0; i < known.size(); i++)
	{
		if (!knownIdx.count(known[i].abilityId)) knownIdx[known[i].abilityId] = i;
		usedSlots.insert(known[i].slot);
	}
	std::map<uint32, bool> loadedIds;
	std::set<uint16> loadedSlots;
	for (const MarginAbility &a : loaded)
	{
		loadedIds[a.abilityId] = true;
		loadedSlots.insert(a.slot);
	}

	PreparedStatement stmt("SELECT `abilityId`, `level` FROM `abilities` WHERE `charId` = ?0");
	stmt.SetUInt64(0, charId);
	scoped_ptr<QueryResult> result(sDatabase.QueryPrepared(&stmt));
	int added = 0;
	if (result)
	{
		do
		{
			Field *field = result->Fetch();
			const uint16 abilityId = field[0].GetUInt16();
			const uint16 level = std::max<uint16>(1, field[1].GetUInt16());
			if (abilityId == 0 || abilityId >= 0x200000) continue;
			auto k = knownIdx.find(abilityId);
			if (k == knownIdx.end())
			{
				// 1. Prefer an unused slot < 0x0208 (e.g. slots 399, 451 in packet9)
				uint16 chosenSlot = kMaxClientAbilitySlots;
				for (uint16 s = 0; s < kMaxClientAbilitySlots; ++s)
				{
					if (!usedSlots.count(s))
					{
						chosenSlot = s;
						break;
					}
				}
				if (chosenSlot < kMaxClientAbilitySlots)
				{
					MarginAbility a; a.slot = chosenSlot; a.abilityId = abilityId; a.level = level;
					usedSlots.insert(chosenSlot);
					knownIdx[abilityId] = known.size();
					known.push_back(a);
					k = knownIdx.find(abilityId);
				}
				else
				{
					// 2. Replace a non-loaded tail entry in known (keeping its valid slot < 0x0208)
					for (size_t idx = known.size(); idx > 0; --idx)
					{
						size_t r = idx - 1;
						if (known[r].slot < kMaxClientAbilitySlots &&
						    !loadedSlots.count(known[r].slot) &&
						    !loadedIds.count(known[r].abilityId))
						{
							knownIdx.erase(known[r].abilityId);
							known[r].abilityId = abilityId;
							known[r].level = level;
							knownIdx[abilityId] = r;
							k = knownIdx.find(abilityId);
							break;
						}
					}
				}
			}
			else if (known[k->second].level < level)
				known[k->second].level = level;
			if (k != knownIdx.end() && !loadedIds.count(abilityId))
			{
				MarginAbility a = known[k->second];
				a.level = level;
				loaded.push_back(a);
				loadedIds[abilityId] = true;
				loadedSlots.insert(a.slot);
				added++;
			}
		} while (result->NextRow());
	}
	knownOut = EncodeMarginAbilities(known);
	loadedOut = EncodeMarginAbilities(loaded);
	DEBUG_LOG(format("Margin: abilities for char %1%: %2% known, %3% loaded (%4% from the character's loadout)")
		% charId % known.size() % loaded.size() % added);
}

